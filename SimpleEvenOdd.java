public class SimpleEvenOdd {
    public static  void main(String[] args) {
        int num = 4; // Yahan aap koi bhi number rakh sakte hain
        
        if (num % 2 == 0) {
            System.out.println(num + " is Even");
        } else {
            System.out.println(num + " is Odd");
        }
    }
}
